    inline std::vector<std::uint8_t> buildMask (int W, int H)
    {
        juce::Image img (juce::Image::RGB, W, H, true);
        {
            juce::Graphics g (img);
            g.fillAll (juce::Colours::black);

            auto toPath = [W, H] (const std::vector<float>& v)
            {
                juce::Path path;
                for (size_t i = 0; i + 1 < v.size(); i += 2)
                {
                    const float x = (v[i] + 180.0f) / 360.0f * (float) W;
                    const float y = (90.0f - v[i + 1]) / 180.0f * (float) H;
                    if (i == 0) path.startNewSubPath (x, y); else path.lineTo (x, y);
                }
                path.closeSubPath();
                return path;
            };

            g.setColour (juce::Colours::white);
            for (auto& poly : landPolys()) g.fillPath (toPath (poly));
            g.setColour (juce::Colours::black);
            for (auto& poly : waterPolys()) g.fillPath (toPath (poly));
        }

        std::vector<std::uint8_t> mask ((size_t) (W * H));
        juce::Image::BitmapData bd (img, juce::Image::BitmapData::readOnly);
        for (int y = 0; y < H; ++y)
            for (int x = 0; x < W; ++x)
                mask[(size_t) (y * W + x)] = bd.getPixelColour (x, y).getRed();
        return mask;
    }
